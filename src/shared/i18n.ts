export type Lang = 'en' | 'pt-BR';
const DICTS: Record<Lang, Record<StringKey, string>> = { en, 'pt-BR': ptBR };

export function resolveLang(setting: 'system' | Lang, systemLocales: readonly string[]): Lang {
  if (setting !== 'system') return setting;
  return systemLocales.some((l) => l.toLowerCase().startsWith('pt')) ? 'pt-BR' : 'en';
}

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k === 'app' ? APP_NAME : String(vars[k] ?? `{${k}}`)));
}

